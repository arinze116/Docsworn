import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

import type { AuditOutput, AuditSummary, AuditedClaim } from "./types.js";

export function summarizeClaims(claims: AuditedClaim[]): AuditSummary {
  const count = (status: AuditedClaim["observation"]["status"]) =>
    claims.filter((claim) => claim.observation.status === status).length;
  const passed = count("passed");
  const failed = count("failed");
  const evaluated = passed + failed;
  return {
    total: claims.length,
    passed,
    failed,
    unverifiable: count("unverifiable"),
    error: count("error"),
    pending: count("pending"),
    accuracyPercent: evaluated === 0 ? null : Math.round((passed / evaluated) * 100),
  };
}

function icon(status: AuditedClaim["observation"]["status"]): string {
  return { passed: "✅", failed: "❌", unverifiable: "⚠️", error: "⛔", pending: "⏳" }[status];
}

export function renderReport(output: AuditOutput): string {
  const score = output.summary.accuracyPercent === null ? "Not enough executed claims" : `${output.summary.accuracyPercent}%`;
  const lines = [
    "# Documentation Truth Report",
    "",
    `- Repository: ${output.repository}`,
    `- Live target: ${output.targetUrl}`,
    `- Generated: ${output.generatedAt}`,
    `- Claim analysis: ${output.aiMode}`,
    `- Kane evidence: ${output.executionMode}`,
    `- Truth score: **${score}** (${output.summary.passed}/${output.summary.passed + output.summary.failed} executed claims verified)`,
    `- Totals: ${output.summary.total} claims; ${output.summary.failed} false; ${output.summary.unverifiable} unverifiable; ${output.summary.error} errors; ${output.summary.pending} pending`,
    "",
  ];

  for (const audited of output.claims) {
    const { claim, observation } = audited;
    lines.push(
      `## ${icon(observation.status)} ${claim.id}: ${observation.status}`,
      "",
      `> ${claim.claim}`,
      "",
      `- Source: \`${claim.sourceFile}:${claim.line}\``,
      `- Flow type: ${claim.flowType}`,
      `- Kane flow: ${audited.flowPath ? `\`${audited.flowPath}\`` : "not generated"}`,
      `- Observation: ${observation.summary}`,
    );
    if (observation.sessionUrl) lines.push(`- Kane session: ${observation.sessionUrl}`);
    if (audited.suggestedFix) lines.push(`- Suggested documentation: **${audited.suggestedFix}**`);
    if (claim.reason) lines.push(`- Verifiability note: ${claim.reason}`);
    lines.push("");
  }
  lines.push("---", "Generated by Docsworn. Captured fallback results are labelled and are not live execution.", "");
  return lines.join("\n");
}

export async function writeReport(output: AuditOutput, filePath: string): Promise<void> {
  await mkdir(path.dirname(filePath), { recursive: true });
  await writeFile(filePath, renderReport(output), "utf8");
}
